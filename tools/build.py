def cell(label, hexv, cmyk, scale=None, extra=""):
    cls = "light" if is_light(hexv) else ""
    num = f'<span class="n">{scale}</span>' if scale else ""
    return (f'<button class="sw {cls}" style="background:{hexv}" data-hex="{hexv}">'
            f'<span class="nm">{label}{num}</span>'
            f'<span class="cd">{hexv}<br>{cmyk}{extra}</span></button>')


