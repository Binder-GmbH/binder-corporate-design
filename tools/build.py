"""Generate the derived artifacts from tokens/colors.json.

Run after changing a value so the CSS, Sass, swatches, colors.md and the
published page stay in step:

    python3 tools/build.py
"""
import json, pathlib, re

ROOT = pathlib.Path(__file__).resolve().parent.parent
P = json.loads((ROOT / "tokens/colors.json").read_text())
PRIMARY = P["primary"]
GRAYS, REDS = P["grayScale"], P["redScale"]
LABELS = {"white": "White", "gray100": "Gray 100", "gray300": "Gray 300", "gray500": "Gray 500",
          "gray800": "Gray 800", "black": "Black", "binderRed": "BINDER Red",
          "redDark": "Red Dark"}
G = {r["scale"]: r["hex"] for r in GRAYS if r["scale"]}      # gray 100..900
WHITE, BLACK = GRAYS[0]["hex"], GRAYS[-1]["hex"]
RED = PRIMARY["binderRed"]["hex"]


def srgb(c):
    c /= 255
    return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4


def lstar(hexv):
    h = hexv.lstrip("#")
    r, g, b = (int(h[i:i + 2], 16) for i in (0, 2, 4))
    y = 0.2126 * srgb(r) + 0.7152 * srgb(g) + 0.0722 * srgb(b)
    return 116 * y ** (1 / 3) - 16 if y > 0.01 else 903.3 * y


def is_light(hexv):
    return lstar(hexv) > 55


def refs(v):
    return ", ".join(x for x in (v.get("hks"), v.get("pantone"), v.get("ral")) if x) or "—"


def write(rel, text):
    (ROOT / rel).write_text(text)
    print(f"  {rel}")


def slug(name):
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")


def build_css():
    o = [":root {", "  /* BINDER corporate colors — generated by tools/build.py", "",
         "     Nine grays, 100 (lightest) to 900 (darkest), the same direction as CSS",
         "     font-weight. White and black sit outside the ramp, as in Bootstrap. */", ""]
    for row in GRAYS:
        key = f"gray-{row['scale']}" if row["scale"] else slug(row["name"])
        o.append(f"  --binder-{key}: {row['hex']};")
    o += ["", "  /* Reds. BINDER Red and Red Dark are brand colors, not ramp steps. */"]
    for row in REDS:
        key = f"red-{row['scale']}" if row["scale"] else slug(row["name"]).removeprefix("binder-")
        o.append(f"  --binder-{key}: {row['hex']};")
    o += ["", "  /* Sustainability topics */", f"  --binder-green: {P['green']['hex']};",
          "", "  /* Chart colors A–L */"]
    o += [f"  --binder-chart-{c['key'].lower()}: {c['hex']};" for c in P["chart"]]
    o.append("}")
    write("tokens/colors.css", "\n".join(o) + "\n")


def build_scss():
    o = ["// BINDER corporate colors — generated by tools/build.py", "",
         "// White and black sit outside the ramp, as in Bootstrap.",
         f"$white:      {GRAYS[0]['hex']};"]
    o += [f"$gray-{r['scale']}:   {r['hex']};"
          for r in GRAYS if r["scale"]]
    o += [f"$black:      {GRAYS[-1]['hex']};", ""]
    o += ["", "// Reds"]
    for row in REDS:
        name = f"$red-{row['scale']}:" if row["scale"] else f"${slug(row['name'])}:"
        o.append(name.ljust(14) + f"{row['hex']};" )
    o += ["", "$binder-green: " + f"{P['green']['hex']};", "", "// Chart colors A–L"]
    o += [f"$chart-{c['key'].lower()}:".ljust(14) + f"{c['hex']};" for c in P["chart"]]
    write("tokens/colors.scss", "\n".join(o) + "\n")


def build_swatch(rows, rel, cell=110, height=104):
    width = cell * len(rows)
    o = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" '
         f'viewBox="0 0 {width} {height}" role="img">',
         f'<rect width="{width}" height="{height}" fill="#ffffff"/>']
    for i, row in enumerate(rows):
        x, hexv = i * cell, row["hex"]
        label = row.get("label") or row.get("key") or ""
        o += [f'<rect x="{x+4}" y="4" width="{cell-8}" height="56" fill="{hexv}" '
              f'stroke="{G[300]}" stroke-width="1"/>',
              f'<text x="{x+cell//2}" y="76" text-anchor="middle" '
              f'font-family="Arial,Helvetica,sans-serif" font-size="11" font-weight="bold" '
              f'fill="#000000">{label}</text>',
              f'<text x="{x+cell//2}" y="92" text-anchor="middle" '
              f'font-family="Arial,Helvetica,sans-serif" font-size="10" fill="{G[700]}">{hexv}</text>']
    o.append("</svg>")
    write(rel, "\n".join(o) + "\n")


